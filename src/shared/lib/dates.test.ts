import { describe, it, expect } from 'vitest'
import { formatDay, formatLastSeen } from '@/shared/lib/dates'

// Пояс тестов — Europe/Moscow, он же UTC+3, прибит в src/test/setup.ts.
// Часы в фикстурах указаны в UTC, ожидания — в местном времени: расхождение
// между ними и есть то, ради чего эти проверки написаны.
const NOW = new Date('2026-10-20T12:00:00Z') // 15:00 по местному, 20 октября

describe('formatDay', () => {
  it('пишет дату цифрами через точку', () => {
    expect(formatDay('2026-06-15T10:00:00Z')).toBe('15.06.2026')
  })

  // Тот самый случай, ради которого даты перестали быть UTC: находка в половине
  // второго ночи по Москве приходится на предыдущие сутки по Гринвичу.
  it('ночную дату относит к местным суткам, а не к UTC', () => {
    expect(formatDay('2026-06-15T22:30:00Z')).toBe('16.06.2026')
  })

  it('на пустой дате молчит прочерком, а не «Invalid Date»', () => {
    expect(formatDay('')).toBe('—')
    expect(formatDay('вчера')).toBe('—')
  })
})

describe('formatLastSeen', () => {
  it('сегодняшнее время пишет словом и часами', () => {
    expect(formatLastSeen('2026-10-20T15:42:00Z', NOW)).toBe('Сегодня, 18:42')
  })

  it('вчерашнее отличает от сегодняшнего', () => {
    expect(formatLastSeen('2026-10-19T20:10:00Z', NOW)).toBe('Вчера, 23:10')
  })

  // Дальше вчерашнего слова не помогают: нужна дата.
  it('старое показывает датой', () => {
    expect(formatLastSeen('2026-10-02T08:00:00Z', NOW)).toBe('02.10.2026')
  })

  it('без данных отвечает прочерком', () => {
    expect(formatLastSeen('', NOW)).toBe('—')
  })
})
