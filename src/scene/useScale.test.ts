import { describe, it, expect } from 'vitest'
import { assetScaleFor, scaleFor } from '@/scene/useScale'

describe('scaleFor', () => {
  // Единицы больше нет ни на одной ширине: при ней основной текст выходил шесть
  // физических пикселей, а подписи — четыре. Замер на 375: 12px против 6px.
  it('на узком экране держит двойку, а не единицу', () => {
    expect(scaleFor(320)).toBe(2)
    expect(scaleFor(375)).toBe(2)
    expect(scaleFor(639)).toBe(2)
  })

  it('поднимает масштаб ступенями по ширине окна', () => {
    expect(scaleFor(640)).toBe(2)
    expect(scaleFor(1280)).toBe(2)
    expect(scaleFor(2560)).toBe(4)
  })

  // Соседние ступени слишком похожи, чтобы перекладывать сцену на каждые 640 точек.
  it('пропускает нечётные ступени', () => {
    expect(scaleFor(1920)).toBe(2)
    expect(scaleFor(2559)).toBe(2)
  })

  it('не превышает потолок — иначе интерфейс станет крупнее экрана', () => {
    expect(scaleFor(5120)).toBe(4)
    expect(scaleFor(99999)).toBe(4)
  })

  /**
   * Весь сайт считается в точках сетки на `--s`, поэтому настройку шрифта
   * в браузере он не слышал вовсе. Теперь она поднимает ступень — но только
   * поднимает и только там, где для ступени есть место.
   */
  it('поднимает ступень, когда человек увеличил системный шрифт', () => {
    expect(scaleFor(1366, 16, 768)).toBe(2)
    expect(scaleFor(1366, 24, 768)).toBe(3)
    expect(scaleFor(1920, 32, 1080)).toBe(4)
  })

  it('не опускает ступень, когда шрифт мельче обычного', () => {
    expect(scaleFor(1366, 8, 768)).toBe(2)
    expect(scaleFor(2560, 8, 1440)).toBe(4)
  })

  // На телефоне поднимать некуда: замер показал, что там влезает только двойка.
  it('на телефоне не поднимает: места нет', () => {
    expect(scaleFor(375, 32, 667)).toBe(2)
    expect(scaleFor(393, 24, 852)).toBe(2)
  })

  /**
   * По ширине на ноутбуке помещается и четвёрка, но книге остаётся десять строк
   * вместо двадцати двух. Высота — настоящее ограничение, стол там заперт
   * в один экран.
   */
  it('считает потолок по высоте, а не только по ширине', () => {
    expect(scaleFor(1366, 64, 768)).toBe(3)
    expect(scaleFor(1366, 64, 900)).toBe(4)
    expect(scaleFor(1366, 64, 1440)).toBe(6)
  })

  it('не поднимает выше того, что помещается', () => {
    expect(scaleFor(820, 64, 1180)).toBe(5)
    expect(scaleFor(2560, 64, 1440)).toBe(6)
  })

  it('переживает нечитаемый размер шрифта', () => {
    expect(scaleFor(1366, Number.NaN)).toBe(2)
    expect(scaleFor(1366, 0)).toBe(2)
  })

  it('всегда возвращает целое число: дробный масштаб мылит пиксели', () => {
    for (const width of [321, 700, 1001, 1439, 2733]) {
      expect(Number.isInteger(scaleFor(width))).toBe(true)
    }
  })
})

describe('assetScaleFor', () => {
  // Сверено с референсом: лампа там 108×232 при ширине окна 1280, а lamp.png —
  // 54×116. Значит предметы идут в том же масштабе, что и интерфейс, а не вдвое мельче.
  it('совпадает с масштабом интерфейса', () => {
    expect(assetScaleFor(1280)).toBe(2)
    expect(assetScaleFor(2560)).toBe(4)
  })

  it('не опускается ниже двойки', () => {
    expect(assetScaleFor(320)).toBe(2)
    expect(assetScaleFor(1000)).toBe(2)
  })

  it('всегда целый', () => {
    for (const width of [321, 700, 1279, 1920, 2733, 5120]) {
      expect(Number.isInteger(assetScaleFor(width))).toBe(true)
    }
  })
})
