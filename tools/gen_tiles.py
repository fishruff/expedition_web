"""Тайлы, нарисованные по палитре проекта.

Дерево стола было фотографической текстурой 512×512 в 66 КБ: мелкое зерно,
плавные переходы, сотни оттенков. Поверх него лежат предметы по 1–3 КБ,
нарисованные крупной точкой и десятком цветов. Это и есть «сцена собрана
из разных игр» — ровно то, о чём предупреждает docs/art/README.md.

Здесь доски нарисованы той же крупностью, что и предметы, и той же палитрой,
что и рамки. Шов тайла проверяется его собственной раскладкой: рисунок
повторяется по обеим осям, поэтому стыки обязаны сходиться.
"""
import sys
sys.path.insert(0, 'tools')
from pixelize import write_png

# Палитра снята с предметов — та же, что у рамок в gen_frames.py.
# Тона держатся близко друг к другу: столешница под лампой почти одноцветна,
# а рисунок ей дают волокно и редкие стыки, а не разница досок.
SEAM = (31, 21, 13, 255)
DARK = (46, 32, 21, 255)
BASE = (63, 45, 30, 255)
WARM = (72, 52, 34, 255)
LIGHT = (88, 64, 42, 255)

# Доски различаются едва-едва. С заметной разницей стол читается полосатым:
# глаз видит чередование рядов, а не пол.
PLANKS = [BASE, WARM, BASE, WARM, BASE, WARM]

SIZE = 192
# Доска высокая: низкая с частыми стыками читается кирпичной кладкой, а не полом.
PLANK_H = 32
# Стык не в каждом ряду — доски длинные, и торцы попадаются редко.
JOINTS = {1: 40, 3: 150, 4: 96}


def rnd(x, y, salt=0):
    """Постоянный шум: тот же рисунок при каждом запуске, иначе тайл не воспроизвести."""
    n = (x * 73856093) ^ (y * 19349663) ^ (salt * 83492791)
    n = (n ^ (n >> 13)) * 1274126177
    return (n ^ (n >> 16)) & 0xffff


def wood(size=SIZE, plank_h=PLANK_H):
    px = [[list(BASE) for _ in range(size)] for _ in range(size)]

    for y in range(size):
        row = y // plank_h
        in_plank = y % plank_h
        base = PLANKS[row % len(PLANKS)]

        for x in range(size):
            if in_plank == 0:
                c = DARK                               # щель между досками
            elif in_plank == 1:
                c = base                               # тень в щели почти сошла
            elif in_plank == plank_h - 1:
                c = WARM if rnd(x, y) % 5 == 0 else base
            else:
                c = base
                # Волокно: длинные штрихи вдоль доски. Ключ по x // 12 растягивает
                # их горизонтально, иначе выходит равномерная пыль.
                #
                # Штрихов нарочно мало и они близки по тону к доске. Стол — фон:
                # если его рисунок читается наравне с книгой, они спорят за взгляд,
                # и выигрывает тот, кто ярче, а не тот, кто важнее.
                streak = rnd(x // 12, y, 1) % 13
                if streak == 0:
                    c = DARK
                elif streak == 1:
                    c = WARM if base is not WARM else BASE

            px[y][x] = list(c)

        joint = JOINTS.get(row % len(PLANKS))
        if joint is not None and in_plank > 1:
            px[y][joint] = list(SEAM)
            px[y][(joint + 1) % size] = list(DARK)

    # Сучок один на весь тайл: два уже читаются узором.
    cx, cy = 120, 76
    for dy in range(-3, 4):
        for dx in range(-5, 6):
            d = dx * dx + dy * dy * 4
            if d <= 20:
                px[(cy + dy) % size][(cx + dx) % size] = list(SEAM if d <= 5 else DARK)

    return px


write_png('public/assets/wood-tile.png', wood())
print('wood-tile.png 192×192 — длинные доски, палитра предметов')
